//! THE PROTECTED-PROPERTY LEDGER'S CHECKER — "is the verification boundary complete?"
//! as a failing test instead of a review question.
//!
//! `docs/architecture/protected-properties.toml` maps every protected property
//! `docs/architecture/protected-properties.md` declares, every execution construct its
//! `oci-constructs` table declares shipped, and every registered operational crash
//! boundary to the CELLS that pin it: real `#[test]` functions, named by package, test binary and
//! test path exactly as nextest names them. This file refuses, and nothing else:
//!
//! 1. a protected-property bullet in the properties doc with no ledger entry, a ledger
//!    property the doc does not declare, or a ledger statement that is not the doc's
//!    bullet verbatim (whitespace-normalized);
//! 2. a row of the properties doc's `oci-constructs` table with no ledger construct, or a
//!    ledger construct the table does not name;
//! 3. a registered crash boundary (`kata_core::fault_inject::OPERATIONAL_CRASH_BOUNDARIES`,
//!    read, not transcribed) with no ledger entry or filed under another family, a
//!    ledger boundary that is no longer registered, and a family with no entry;
//! 4. a cell whose package, test binary or test function does not exist — resolved
//!    through the module tree from the target's own `src_path` (cargo metadata), so a
//!    renamed test, a moved module or a deleted binary is a named failure;
//! 5. a cell whose recorded KIND disagrees with how it runs: `host-free` is an
//!    un-ignored test in a file carrying no live-capability marker, selected by a gate
//!    `cargo nextest run` that does not pass `--run-ignored`; `live` is ignored or in a
//!    marker-carrying file, and selected by one that does;
//! 6. a cell whose recorded LAYER is not the one the gate recipes resolve for it (the
//!    lowest layer whose root recipes — the ledger's `[layers]` — STRUCTURALLY reach an
//!    invocation selecting it), and a layer root that names no recipe;
//! 7. an entry missing a required class of cell — at least one `host-free` cell, a
//!    `live` cell at L1 when it is host-dependent — that no `unpinned` record names
//!    (there is one engine, so no per-profile path class); an `unpinned` record for a class
//!    that is now pinned (stale) or with no reason; a duplicate entry id or a duplicate
//!    cell in one entry (`every_ledger_entry_is_pinned_or_names_its_gap`); and, in its
//!    own test so a red names exactly the decisions pending, every `unpinned` record —
//!    a missing class or a named clause no cell pins — whose `acknowledged` is not
//!    `true` (`every_ledger_gap_is_acknowledged`; acknowledged ones pass and are
//!    printed as warnings);
//! 8. a citation whose file is absent, whose anchor names no heading of that file, or
//!    whose quote is not in it.
//!
//! WHAT IT CANNOT SEE, stated so it is not implied: whether a cell's assertions pin the
//! property (the `pins` text is the author's reading — a reviewer's reconciliation of
//! the ledger against their own construct→cell map is what checks it); a
//! capability skip inside a helper defined in another file; whether a gate recipe
//! propagates a selected invocation's FAILURE (an invocation whose segment is followed
//! by `||` is not counted, and nothing else about exit handling is read); an invocation
//! whose filter is built from a recipe PARAMETER (it proves nothing and is not counted);
//! the environment a live invocation runs under (a recipe that forgot its capability
//! knob still counts); a test generated by a macro (it cannot be resolved, so it cannot be a
//! cell).
//!
//! It reads sources, manifests and the justfile only: `cargo metadata --no-deps` (no
//! build, no resolution — measured to return in 0.06 s while another cargo held the build
//! lock) and Just's own JSON dump. It runs no test it names.

