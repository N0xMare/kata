#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum RunIgnored {
    Default,
    All,
    Only,
}

/// One `cargo nextest run` a layer's root recipes structurally reach.
#[derive(Debug)]
struct Invocation {
    layer: Layer,
    recipe: String,
    packages: Vec<String>,
    filters: Vec<Filterset>,
    positional: Vec<String>,
    profile: String,
    run_ignored: RunIgnored,
    ignore_default_filter: bool,
}

/// nextest options that consume the next word.
const NEXTEST_VALUE_FLAGS: &[&str] = &[
    "-E",
    "--filterset",
    "--filter-expr",
    "-P",
    "--profile",
    "--run-ignored",
    "-p",
    "--package",
    "--test-threads",
    "-j",
    "--success-output",
    "--failure-output",
    "--status-level",
    "--final-status-level",
    "--binaries-metadata",
    "--cargo-metadata",
    "--no-tests",
    "--manifest-path",
    "--target-dir",
    "--retries",
    "--message-format",
    "--partition",
    "--color",
    "--features",
    "-F",
    "--archive-file",
];

/// `name=value` assignments at the start of a body line, for resolving `-E "$name"`.
/// A name assigned twice is ambiguous and resolves to nothing.
fn body_assignments(body: &str, recipe: &str) -> BTreeMap<String, Option<String>> {
    let mut assignments: BTreeMap<String, Option<String>> = BTreeMap::new();
    for line in logical_lines(body, recipe) {
        let Ok(tokens) = shell_tokens(&line.text) else {
            continue;
        };
        let [ShellToken::Word { text, dynamic }] = tokens.as_slice() else {
            continue;
        };
        if !is_assignment(text) {
            continue;
        }
        let (name, value) = text.split_once('=').expect("an assignment has `=`");
        let value = (!*dynamic).then(|| value.to_string());
        assignments
            .entry(name.to_string())
            .and_modify(|existing| *existing = None)
            .or_insert(value);
    }
    assignments
}

fn resolve_word(
    word: &str,
    dynamic: bool,
    assignments: &BTreeMap<String, Option<String>>,
) -> Option<String> {
    if dynamic || word.contains(DYNAMIC) {
        return None;
    }
    if !word.contains('$') {
        return Some(word.to_string());
    }
    // Only a WHOLE-word reference (`$name` or `${name}`) resolves; anything built
    // around one is not a value this file can know.
    let name = word
        .strip_prefix("${")
        .and_then(|rest| rest.strip_suffix('}'))
        .or_else(|| word.strip_prefix('$'))?;
    if !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return None;
    }
    assignments.get(name).cloned().flatten()
}

fn is_redirection(word: &str) -> bool {
    let rest = word.trim_start_matches(|c: char| c.is_ascii_digit());
    rest.starts_with('>') || rest.starts_with('<')
}

/// One command of a shell line: its words (each with whether a Just interpolation
/// built it) and the separator that follows it.
#[derive(Default)]
struct Segment<'a> {
    words: Vec<(&'a str, bool)>,
    after: Option<Separator>,
}

/// Every `cargo nextest run` on one logical line that can put a cell in a layer. Left
/// out, because each proves nothing: one that runs nothing (`--no-run`), one followed by
/// `||`, and one whose selection (`-E`, `-P`, `-p`, `--run-ignored`, a name filter) is
/// built from a recipe parameter or a shell value this file cannot resolve.
fn invocations_on_line(
    layer: Layer,
    recipe: &str,
    line: &str,
    assignments: &BTreeMap<String, Option<String>>,
) -> Vec<Invocation> {
    if !line.contains("nextest") {
        return Vec::new();
    }
    let tokens = shell_tokens(line).unwrap_or_else(|error| {
        panic!("unsupported shell in gate recipe `{recipe}`: {error}: {line}")
    });
    let mut segments = vec![Segment::default()];
    for token in &tokens {
        match token {
            ShellToken::Word { text, dynamic } => {
                let segment = segments.last_mut().expect("one segment");
                segment.words.push((text.as_str(), *dynamic));
            }
            ShellToken::Separator(separator) => {
                segments.last_mut().expect("one segment").after = Some(*separator);
                segments.push(Segment::default());
            }
        }
    }
    let mut found = Vec::new();
    for Segment { words, after } in segments {
        let mut at = 0;
        while words.get(at).is_some_and(|(word, _)| is_assignment(word)) {
            at += 1;
        }
        if words.get(at).is_some_and(|(word, _)| *word == "env") {
            at += 1;
            while let Some((word, _)) = words.get(at) {
                if *word == "-u" || *word == "--unset" {
                    at += 2;
                } else if word.starts_with('-') || is_assignment(word) {
                    at += 1;
                } else {
                    break;
                }
            }
        }
        if words.get(at).is_some_and(|(word, _)| *word == "exec") {
            at += 1;
        }
        let command: Vec<&str> = words[at.min(words.len())..]
            .iter()
            .map(|(word, _)| *word)
            .collect();
        let offset = match command.as_slice() {
            ["cargo", "nextest", "run", ..] => 3,
            ["cargo", toolchain, "nextest", "run", ..] if toolchain.starts_with('+') => 4,
            _ => continue,
        };
        if after == Some(Separator::Or) {
            // `cargo nextest run … || …` does not fail its recipe on a red suite.
            continue;
        }
        let args = &words[at + offset..];
        let mut invocation = Invocation {
            layer,
            recipe: recipe.to_string(),
            packages: Vec::new(),
            filters: Vec::new(),
            positional: Vec::new(),
            profile: "default".to_string(),
            run_ignored: RunIgnored::Default,
            ignore_default_filter: false,
        };
        let mut readable = true;
        let mut no_run = false;
        let mut index = 0;
        while index < args.len() {
            let (word, dynamic) = args[index];
            if is_redirection(word) {
                // A bare operator (`>`, `2>`, `>>`) takes the next word as its target;
                // `2>&1` or `>file` is complete in itself.
                let operator = word.trim_start_matches(|c: char| c.is_ascii_digit());
                index += if operator.chars().all(|c| matches!(c, '>' | '<' | '&')) {
                    2
                } else {
                    1
                };
                continue;
            }
            let (flag, inline_value) = match word.split_once('=') {
                Some((flag, value)) if flag.starts_with("--") => (flag, Some(value.to_string())),
                _ => (word, None),
            };
            if NEXTEST_VALUE_FLAGS.contains(&flag) {
                let raw = if let Some(value) = inline_value {
                    Some((value, false))
                } else {
                    index += 1;
                    args.get(index)
                        .map(|(value, dynamic)| ((*value).to_string(), *dynamic))
                };
                // Only the options that decide SELECTION must be read; any other
                // option's value (a metadata path, a thread count) is consumed unread.
                if !matches!(
                    flag,
                    "-E" | "--filterset"
                        | "--filter-expr"
                        | "-P"
                        | "--profile"
                        | "-p"
                        | "--package"
                        | "--run-ignored"
                ) {
                    index += 1;
                    continue;
                }
                let Some(value) =
                    raw.and_then(|(value, dynamic)| resolve_word(&value, dynamic, assignments))
                else {
                    readable = false;
                    index += 1;
                    continue;
                };
                match flag {
                    "-E" | "--filterset" | "--filter-expr" => {
                        let parsed = parse_filterset(&value).unwrap_or_else(|error| {
                            panic!("gate recipe `{recipe}`: {error}\n  line: {line}")
                        });
                        invocation.filters.push(parsed);
                    }
                    "-P" | "--profile" => invocation.profile = value,
                    "-p" | "--package" => invocation.packages.push(value),
                    "--run-ignored" => {
                        invocation.run_ignored = match value.as_str() {
                            "all" => RunIgnored::All,
                            "only" | "ignored-only" => RunIgnored::Only,
                            "default" => RunIgnored::Default,
                            other => {
                                panic!("gate recipe `{recipe}`: unknown --run-ignored `{other}`")
                            }
                        };
                    }
                    _ => {}
                }
            } else if word == "--no-run" {
                no_run = true;
            } else if word == "--ignore-default-filter" {
                invocation.ignore_default_filter = true;
            } else if word.starts_with('-') {
                // A boolean option (`--workspace`, `--no-fail-fast`, ...).
            } else if let Some(value) = resolve_word(word, dynamic, assignments) {
                invocation.positional.push(value);
            } else {
                readable = false;
            }
            index += 1;
        }
        if no_run || !readable {
            continue;
        }
        assert!(
            invocation.positional.is_empty() || invocation.filters.is_empty(),
            "gate recipe `{recipe}` mixes name filters and a filterset, whose combination this \
             file does not model: {line}"
        );
        found.push(invocation);
    }
    found
}

/// Every invocation each layer's roots structurally reach. A line inside a shell
/// control structure runs only POSSIBLY, so it cannot put a cell in a layer.
fn layer_invocations(justfile: &Justfile, roots: &[(Layer, &[String])]) -> Vec<Invocation> {
    let mut invocations = Vec::new();
    for (layer, names) in roots {
        for root in *names {
            for (recipe, body) in structurally_required_recipes(justfile, root) {
                let assignments = body_assignments(&body, &recipe);
                for line in logical_lines(&body, &recipe) {
                    if line.inside_control {
                        continue;
                    }
                    invocations.extend(invocations_on_line(
                        *layer,
                        &recipe,
                        &line.text,
                        &assignments,
                    ));
                }
            }
        }
    }
    invocations
}

fn selects(
    invocation: &Invocation,
    defaults: &BTreeMap<String, Filterset>,
    test: &TestIdentity<'_>,
    ignored: bool,
) -> bool {
    if !invocation.packages.is_empty() && !invocation.packages.iter().any(|p| p == test.package) {
        return false;
    }
    if !invocation.filters.is_empty() && !invocation.filters.iter().any(|f| f.matches(test)) {
        return false;
    }
    if !invocation.positional.is_empty()
        && !invocation
            .positional
            .iter()
            .any(|name| test.test.contains(name.as_str()))
    {
        return false;
    }
    if !invocation.ignore_default_filter {
        let default = defaults
            .get(&invocation.profile)
            .or_else(|| defaults.get("default"));
        if default.is_some_and(|filter| !filter.matches(test)) {
            return false;
        }
    }
    match invocation.run_ignored {
        RunIgnored::Default => !ignored,
        RunIgnored::All => true,
        RunIgnored::Only => ignored,
    }
}

/// The layer that runs `test` AS `kind`: the lowest layer with an invocation that
/// selects it without `--run-ignored` (host-free) or with it (live).
fn resolved_layer(
    invocations: &[Invocation],
    defaults: &BTreeMap<String, Filterset>,
    test: &TestIdentity<'_>,
    ignored: bool,
    kind: Kind,
) -> Option<(Layer, String)> {
    invocations
        .iter()
        .filter(|invocation| match kind {
            Kind::HostFree => invocation.run_ignored == RunIgnored::Default,
            Kind::Live => invocation.run_ignored != RunIgnored::Default,
        })
        .filter(|invocation| selects(invocation, defaults, test, ignored))
        .min_by_key(|invocation| invocation.layer)
        .map(|invocation| (invocation.layer, invocation.recipe.clone()))
}

/// Rules 4–6 for one cell.
fn cell_failures(
    label: &str,
    cell: &Cell,
    targets: &BTreeMap<String, Vec<Target>>,
    cache: &mut SourceCache,
    invocations: &[Invocation],
    defaults: &BTreeMap<String, Filterset>,
) -> Vec<String> {
    let id = nextest_id(&cell.package, &cell.binary, &cell.test);
    let target = match find_target(targets, cell) {
        Ok(target) => target,
        Err(error) => return vec![format!("{label}: cell {id}: {error}")],
    };
    let resolved = match resolve_test_fn(cache, &target.src_path, &cell.test) {
        Ok(resolved) => resolved,
        Err(error) => return vec![format!("{label}: cell {id} does not exist: {error}")],
    };
    let mut failures = Vec::new();
    let marked = file_carries_a_live_capability_marker(&resolved.file);
    match cell.kind {
        Kind::HostFree if resolved.ignored => failures.push(format!(
            "{label}: cell {id} is recorded host-free and is `#[ignore]`d, so the suite never runs it"
        )),
        Kind::HostFree if marked => failures.push(format!(
            "{label}: cell {id} is recorded host-free and its file {} carries a live-capability \
             marker, so it can return without asserting on a host that lacks the capability",
            resolved.file.display()
        )),
        Kind::Live if !resolved.ignored && !marked => failures.push(format!(
            "{label}: cell {id} is recorded live and is neither `#[ignore]`d nor in a file \
             carrying a live-capability marker — nothing about it needs the host"
        )),
        _ => {}
    }
    let binary_id = match target.kind {
        TargetKind::Lib => cell.package.clone(),
        TargetKind::Bin => format!("{}::bin/{}", cell.package, target.name),
        TargetKind::Test => format!("{}::{}", cell.package, target.name),
    };
    let identity = TestIdentity {
        package: &cell.package,
        binary_name: &target.name,
        binary_id,
        kind: target.kind,
        test: &cell.test,
    };
    match resolved_layer(
        invocations,
        defaults,
        &identity,
        resolved.ignored,
        cell.kind,
    ) {
        None => failures.push(format!(
            "{label}: cell {id} is recorded {:?} {} and NO gate invocation runs it as {}",
            cell.layer,
            kind_word(cell.kind),
            kind_word(cell.kind)
        )),
        Some((layer, recipe)) if layer != cell.layer => failures.push(format!(
            "{label}: cell {id} is recorded {:?} and the gate recipes run it in {layer:?} (`just \
             {recipe}`)",
            cell.layer
        )),
        Some(_) => {}
    }
    failures
}

fn kind_word(kind: Kind) -> &'static str {
    match kind {
        Kind::HostFree => "host-free",
        Kind::Live => "live",
    }
}

fn report(failures: &[String], warnings: &[String]) -> String {
    let mut out = String::new();
    for failure in failures {
        let _ = writeln!(out, "  FAIL {failure}");
    }
    for warning in warnings {
        let _ = writeln!(out, "  WARN {warning}");
    }
    out
}

