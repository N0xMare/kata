// ─── the ledger's schema ──────────────────────────────────────────────────────

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Ledger {
    schema: u32,
    layers: Layers,
    #[serde(default)]
    property: Vec<Entry>,
    #[serde(default)]
    construct: Vec<Entry>,
    #[serde(default)]
    crash_family: Vec<CrashFamily>,
}

/// The gate recipes whose STRUCTURAL closure defines each layer. The ledger owns this
/// map so that moving the tiers is one data edit beside the cells it moves, and
/// `the_layer_roots_exist` refuses a root that names no recipe, so renaming a tier's
/// recipe reddens the checker instead of silently emptying a layer.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Layers {
    #[serde(rename = "L1")]
    l1: Vec<String>,
    #[serde(rename = "L2")]
    l2: Vec<String>,
}

impl Layers {
    fn roots(&self) -> Vec<(Layer, &[String])> {
        vec![
            (Layer::L1, self.l1.as_slice()),
            (Layer::L2, self.l2.as_slice()),
        ]
    }
}

/// A protected property or a shipped construct.
///
/// For a property, `statement` is the properties doc's bullet verbatim (rule 1 compares
/// them); for a construct, it is a one-line description and its citations carry the
/// proof that the properties doc says what the entry claims.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Entry {
    id: String,
    statement: String,
    host_dependent: bool,
    #[serde(default)]
    citation: Vec<Citation>,
    #[serde(default)]
    cell: Vec<Cell>,
    #[serde(default)]
    unpinned: Vec<Unpinned>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct CrashFamily {
    family: String,
    #[serde(default)]
    boundary: Vec<Boundary>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Boundary {
    name: String,
    #[serde(default)]
    cell: Vec<Cell>,
    #[serde(default)]
    unpinned: Vec<Unpinned>,
}

/// `at` is `<repo-relative path>#<heading anchor>`; `quote` must occur in that file.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Citation {
    at: String,
    quote: String,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Eq, PartialOrd, Ord)]
#[serde(deny_unknown_fields)]
struct Cell {
    /// Cargo package name.
    package: String,
    /// The test binary: an integration-test target's name, `lib` for the package's
    /// library unit tests, or `bin/<name>` for a binary target's unit tests.
    binary: String,
    /// The test's full path inside that binary, exactly as nextest lists it.
    test: String,
    kind: Kind,
    layer: Layer,
    /// What the cell asserts that pins the entry — the author's reading, for review.
    pins: String,
}

#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq, PartialOrd, Ord)]
#[serde(rename_all = "kebab-case")]
enum Kind {
    HostFree,
    Live,
}

#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq, PartialOrd, Ord)]
enum Layer {
    L1,
    L2,
}

/// A class of pinning an entry lacks, stated rather than implied.
#[derive(Clone, Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Unpinned {
    missing: Missing,
    /// For `missing = "clause"`, the part of the statement the cells do not pin.
    #[serde(default)]
    clause: Option<String>,
    reason: String,
    #[serde(default)]
    acknowledged: bool,
}

#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "kebab-case")]
enum Missing {
    /// No cell at all.
    Cells,
    HostFree,
    /// A live cell in the PUSH tier (L1): a host-dependent claim's proof cannot wait
    /// for the nightly.
    #[serde(rename = "live-l1")]
    LiveL1,
    /// A named clause of the statement no cell pins; waives no structural class.
    Clause,
}

impl Missing {
    fn describe(self) -> &'static str {
        match self {
            Missing::Cells => "no cell at all",
            Missing::HostFree => "no host-free cell",
            Missing::LiveL1 => "no live cell at L1 although it is host-dependent",
            Missing::Clause => "a clause no cell pins",
        }
    }
}

fn load_ledger() -> Ledger {
    let path = repo_root().join(LEDGER_PATH);
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("reading the ledger {}: {error}", path.display()));
    let ledger: Ledger = toml::from_str(&text)
        .unwrap_or_else(|error| panic!("parsing the ledger {LEDGER_PATH}: {error}"));
    assert_eq!(ledger.schema, 1, "{LEDGER_PATH}: unknown schema");
    ledger
}

/// Every entry, as one shape, labelled for failure messages.
struct EntryView<'a> {
    label: String,
    host_dependent: bool,
    cells: &'a [Cell],
    unpinned: &'a [Unpinned],
}

fn entry_views(ledger: &Ledger) -> Vec<EntryView<'_>> {
    let mut views = Vec::new();
    for entry in &ledger.property {
        views.push(EntryView {
            label: format!("property `{}`", entry.id),
            host_dependent: entry.host_dependent,
            cells: &entry.cell,
            unpinned: &entry.unpinned,
        });
    }
    for entry in &ledger.construct {
        views.push(EntryView {
            label: format!("construct `{}`", entry.id),
            host_dependent: entry.host_dependent,
            cells: &entry.cell,
            unpinned: &entry.unpinned,
        });
    }
    for family in &ledger.crash_family {
        for boundary in &family.boundary {
            views.push(EntryView {
                label: format!("crash boundary `{}` ({})", boundary.name, family.family),
                host_dependent: false,
                cells: &boundary.cell,
                unpinned: &boundary.unpinned,
            });
        }
    }
    views
}

// ─── rule 1: the protected properties ────────────────────────────────────────

fn normalize_space(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// The bullets under `## Protected properties`, each joined across its wrapped lines.
fn protected_property_bullets(doc: &str) -> Vec<String> {
    let mut lines = doc.lines();
    assert!(
        lines.any(|line| line.trim_end() == PROTECTED_PROPERTIES_HEADING),
        "{PROPERTIES_DOC_PATH} has no `{PROTECTED_PROPERTIES_HEADING}` heading"
    );
    let mut bullets: Vec<String> = Vec::new();
    for line in lines {
        if line.starts_with("## ") {
            break;
        }
        if let Some(bullet) = line.strip_prefix("- ") {
            bullets.push(bullet.to_string());
        } else if line.starts_with("  ")
            && !line.trim().is_empty()
            && let Some(last) = bullets.last_mut()
        {
            last.push(' ');
            last.push_str(line.trim());
        }
    }
    bullets
        .iter()
        .map(|bullet| normalize_space(bullet))
        .collect()
}

fn property_set_failures(bullets: &[String], properties: &[Entry]) -> Vec<String> {
    let mut failures = Vec::new();
    let statements: BTreeMap<String, &str> = properties
        .iter()
        .map(|entry| (normalize_space(&entry.statement), entry.id.as_str()))
        .collect();
    for bullet in bullets {
        if !statements.contains_key(bullet) {
            failures.push(format!(
                "the properties doc declares the protected property \"{bullet}\" and no ledger \
                 property carries that statement verbatim"
            ));
        }
    }
    let declared: BTreeSet<&String> = bullets.iter().collect();
    for (statement, id) in &statements {
        if !declared.contains(statement) {
            failures.push(format!(
                "ledger property `{id}` states \"{statement}\", which is not a bullet of the \
                 properties doc's `{PROTECTED_PROPERTIES_HEADING}`"
            ));
        }
    }
    failures
}

// ─── rule 2: the shipped constructs ──────────────────────────────────────────

/// The ledger ids named in the last column of the properties doc's `oci-constructs` table.
fn construct_table_ids(doc: &str) -> Vec<String> {
    let begin = doc.find(CONSTRUCT_TABLE_BEGIN).unwrap_or_else(|| {
        panic!("{PROPERTIES_DOC_PATH} carries no `{CONSTRUCT_TABLE_BEGIN}` table")
    });
    let end = doc[begin..]
        .find(CONSTRUCT_TABLE_END)
        .unwrap_or_else(|| panic!("{PROPERTIES_DOC_PATH}'s construct table is never closed"))
        + begin;
    let mut ids = Vec::new();
    for line in doc[begin..end].lines().skip(1) {
        let line = line.trim();
        if !line.starts_with('|') || line.starts_with("|---") || line.starts_with("| Construct") {
            continue;
        }
        let cells: Vec<&str> = line.trim_matches('|').split('|').map(str::trim).collect();
        let last = cells.last().copied().unwrap_or_default();
        let id = last.trim_matches('`');
        assert!(
            !id.is_empty() && last.starts_with('`') && last.ends_with('`'),
            "{PROPERTIES_DOC_PATH}: construct-table row `{line}` must end in a backticked ledger id"
        );
        ids.push(id.to_string());
    }
    ids
}

fn construct_set_failures(table_ids: &[String], constructs: &[Entry]) -> Vec<String> {
    let mut failures = Vec::new();
    let ledger_ids: BTreeSet<&str> = constructs.iter().map(|entry| entry.id.as_str()).collect();
    let table: BTreeSet<&str> = table_ids.iter().map(String::as_str).collect();
    for id in &table {
        if !ledger_ids.contains(id) {
            failures.push(format!(
                "the properties doc ships the construct `{id}` and the ledger has no \
                 construct entry for it"
            ));
        }
    }
    for id in &ledger_ids {
        if !table.contains(id) {
            failures.push(format!(
                "ledger construct `{id}` is not a row of the properties doc's \
                 `oci-constructs` table"
            ));
        }
    }
    failures
}

// ─── rule 3: the crash-boundary registry ─────────────────────────────────────

fn crash_registry_failures(
    registry: &[(&str, &str)],
    families: &[&str],
    ledger: &[CrashFamily],
) -> Vec<String> {
    let mut failures = Vec::new();
    let mut filed: BTreeMap<&str, &str> = BTreeMap::new();
    for family in ledger {
        if !families.contains(&family.family.as_str()) {
            failures.push(format!(
                "ledger crash family `{}` is not an `OperationalBoundaryFamily`",
                family.family
            ));
        }
        for boundary in &family.boundary {
            if let Some(previous) = filed.insert(boundary.name.as_str(), family.family.as_str()) {
                failures.push(format!(
                    "crash boundary `{}` is filed twice (under `{previous}` and `{}`)",
                    boundary.name, family.family
                ));
            }
        }
    }
    for (name, family) in registry {
        match filed.get(name) {
            None => failures.push(format!(
                "registered crash boundary `{name}` ({family}) has no ledger entry"
            )),
            Some(filed_under) if filed_under != family => failures.push(format!(
                "crash boundary `{name}` is registered under `{family}` and filed under \
                 `{filed_under}`"
            )),
            Some(_) => {}
        }
    }
    for name in filed.keys() {
        if !registry.iter().any(|(registered, _)| registered == name) {
            failures.push(format!(
                "ledger crash boundary `{name}` is no longer registered in \
                 `OPERATIONAL_CRASH_BOUNDARIES`"
            ));
        }
    }
    for family in families {
        if !ledger.iter().any(|entry| entry.family == *family) {
            failures.push(format!("crash family `{family}` has no ledger entry"));
        }
    }
    failures
}

// ─── rule 7: coverage and acknowledged gaps ──────────────────────────────────

/// One entry's rule-7 verdict.
///
/// `failures` are structural (a required class nobody named, a stale or malformed
/// record, a duplicate cell). `unacknowledged` are well-formed gap records a maintainer
/// has not accepted: they fail a SEPARATE test, so a red names exactly the decisions pending.
/// `acknowledged` pass and are printed, because a gap nobody reads again is a gap nobody
/// owns.
#[derive(Debug, Default, PartialEq, Eq)]
struct Coverage {
    failures: Vec<String>,
    unacknowledged: Vec<String>,
    acknowledged: Vec<String>,
}

fn coverage(view: &EntryView<'_>) -> Coverage {
    let mut verdict = Coverage::default();
    let label = &view.label;

    let mut seen = BTreeSet::new();
    for cell in view.cells {
        if !seen.insert((&cell.package, &cell.binary, &cell.test)) {
            verdict.failures.push(format!(
                "{label} lists the cell {} twice",
                nextest_id(&cell.package, &cell.binary, &cell.test)
            ));
        }
    }

    let mut required = Vec::new();
    if view.cells.is_empty() {
        required.push(Missing::Cells);
    } else {
        if !view.cells.iter().any(|cell| cell.kind == Kind::HostFree) {
            required.push(Missing::HostFree);
        }
        if view.host_dependent
            && !view
                .cells
                .iter()
                .any(|cell| cell.kind == Kind::Live && cell.layer == Layer::L1)
        {
            required.push(Missing::LiveL1);
        }
    }

    for missing in &required {
        if !view
            .unpinned
            .iter()
            .any(|record| record.missing == *missing)
        {
            verdict.failures.push(format!(
                "{label} has {} and no `unpinned` record naming it",
                missing.describe()
            ));
        }
    }
    for record in view.unpinned {
        let what = match (&record.missing, &record.clause) {
            (Missing::Clause, Some(clause)) => format!("the clause \"{clause}\""),
            (Missing::Clause, None) => {
                verdict.failures.push(format!(
                    "{label} has an `unpinned` clause record with no `clause`"
                ));
                continue;
            }
            (missing, _) => missing.describe().to_string(),
        };
        if record.missing != Missing::Clause && !required.contains(&record.missing) {
            verdict.failures.push(format!(
                "{label} carries a STALE `unpinned` record ({what}): that class is pinned now, \
                 so the record claims a gap that no longer exists"
            ));
        } else if record.reason.trim().is_empty() {
            verdict.failures.push(format!(
                "{label}: the `unpinned` record for {what} states no reason"
            ));
        } else if record.acknowledged {
            verdict.acknowledged.push(format!(
                "{label}: UNPINNED, acknowledged — {what}: {}",
                record.reason
            ));
        } else {
            verdict.unacknowledged.push(format!(
                "{label}: UNPINNED and not acknowledged — {what}: {} (only a maintainer sets \
                 `acknowledged = true`)",
                record.reason
            ));
        }
    }
    verdict
}

// ─── rule 8: citations ───────────────────────────────────────────────────────

/// The GitHub-style anchor of a markdown heading.
fn heading_anchor(heading: &str) -> String {
    heading
        .trim_start_matches('#')
        .trim()
        .to_lowercase()
        .chars()
        .filter_map(|ch| match ch {
            ' ' => Some('-'),
            '-' | '_' => Some(ch),
            _ if ch.is_alphanumeric() => Some(ch),
            _ => None,
        })
        .collect()
}

fn citation_failures(label: &str, citation: &Citation, root: &Path) -> Vec<String> {
    let mut failures = Vec::new();
    let Some((path, anchor)) = citation.at.split_once('#') else {
        return vec![format!(
            "{label}: citation `{}` has no `#anchor`",
            citation.at
        )];
    };
    let Ok(text) = std::fs::read_to_string(root.join(path)) else {
        return vec![format!("{label}: cited file `{path}` does not exist")];
    };
    let anchors: BTreeSet<String> = text
        .lines()
        .filter(|line| line.starts_with('#'))
        .map(heading_anchor)
        .collect();
    if !anchors.contains(anchor) {
        failures.push(format!(
            "{label}: `{path}` has no heading whose anchor is `#{anchor}`"
        ));
    }
    if !normalize_space(&text).contains(&normalize_space(&citation.quote)) {
        failures.push(format!(
            "{label}: `{path}` does not contain the quoted text \"{}\"",
            citation.quote
        ));
    }
    failures
}

// ─── rules 4–6: resolving a cell ─────────────────────────────────────────────

fn nextest_id(package: &str, binary: &str, test: &str) -> String {
    if binary == "lib" {
        format!("{package} {test}")
    } else {
        format!("{package}::{binary} {test}")
    }
}

fn find_target<'a>(
    targets: &'a BTreeMap<String, Vec<Target>>,
    cell: &Cell,
) -> Result<&'a Target, String> {
    let Some(package) = targets.get(&cell.package) else {
        return Err(format!(
            "package `{}` is not a workspace member",
            cell.package
        ));
    };
    let (kind, name) = if cell.binary == "lib" {
        (TargetKind::Lib, None)
    } else if let Some(bin) = cell.binary.strip_prefix("bin/") {
        (TargetKind::Bin, Some(bin))
    } else {
        (TargetKind::Test, Some(cell.binary.as_str()))
    };
    package
        .iter()
        .find(|target| target.kind == kind && name.is_none_or(|name| target.name == name))
        .ok_or_else(|| {
            format!(
                "package `{}` has no {} target `{}`",
                cell.package,
                kind.as_str(),
                cell.binary
            )
        })
}

/// A resolved `#[test]` function: the file that defines it and whether it is ignored.
#[derive(Debug, Clone, PartialEq, Eq)]
struct ResolvedFn {
    file: PathBuf,
    ignored: bool,
}

/// Resolve `test_path` (`a::b::name`) from the crate root `src_path`.
fn resolve_test_fn(
    cache: &mut SourceCache,
    src_path: &Path,
    test_path: &str,
) -> Result<ResolvedFn, String> {
    let segments: Vec<&str> = test_path.split("::").collect();
    let (name, modules) = segments
        .split_last()
        .expect("split yields at least one segment");
    let dirs = root_dirs(src_path);
    let items = cache.parse(src_path)?.items.clone();
    resolve_in(cache, &items, src_path, &dirs, modules, name)
}

fn resolve_in(
    cache: &mut SourceCache,
    items: &[syn::Item],
    file: &Path,
    dirs: &ModuleDirs,
    modules: &[&str],
    name: &str,
) -> Result<ResolvedFn, String> {
    let Some((module, rest)) = modules.split_first() else {
        let mut found_non_test = false;
        for item in items {
            let syn::Item::Fn(function) = item else {
                continue;
            };
            if function.sig.ident != name {
                continue;
            }
            if function.attrs.iter().any(is_test_attribute) {
                return Ok(ResolvedFn {
                    file: file.to_path_buf(),
                    ignored: function
                        .attrs
                        .iter()
                        .any(|attr| attr.path().is_ident("ignore")),
                });
            }
            found_non_test = true;
        }
        return Err(if found_non_test {
            format!(
                "`{name}` in {} is a function but not a `#[test]`",
                file.display()
            )
        } else {
            format!("no test function `{name}` in {}", file.display())
        });
    };
    let mut errors = Vec::new();
    for item in items {
        let syn::Item::Mod(declared) = item else {
            continue;
        };
        if declared.ident != *module {
            continue;
        }
        let outcome = match module_source(dirs, declared) {
            ModuleSource::Inline(inline, inner) => {
                resolve_in(cache, inline, file, &inner, rest, name)
            }
            ModuleSource::File(child, inner) => match cache.parse(&child) {
                Ok(parsed) => {
                    let child_items = parsed.items.clone();
                    resolve_in(cache, &child_items, &child, &inner, rest, name)
                }
                Err(error) => Err(error),
            },
        };
        match outcome {
            Ok(resolved) => return Ok(resolved),
            Err(error) => errors.push(error),
        }
    }
    if errors.is_empty() {
        Err(format!("no module `{module}` in {}", file.display()))
    } else {
        Err(errors.join("; "))
    }
}

fn file_carries_a_live_capability_marker(file: &Path) -> bool {
    let source = std::fs::read_to_string(file).unwrap_or_default();
    LIVE_CAPABILITY_MARKERS
        .iter()
        .any(|(marker, _)| source.contains(marker))
}

