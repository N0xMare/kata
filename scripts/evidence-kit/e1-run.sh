#!/usr/bin/env bash
# e1-run.sh EV CASE SURFACE REPO PR: one E1 run, submitted through one surface,
# every oracle read from outside kata (RUNBOOK §3). Run it from the clone (the
# repository under test, its node serving on 127.0.0.1:8400).
#
#   EV       the run's evidence directory (created; must not exist yet)
#   CASE     seeded-pr | public-pr
#   SURFACE  cli (`kata run review --target pr:PR --submit`) |
#            rest (`POST /api/v1/executions`, loopback auth disabled: no token)
#   REPO     the forge repository, OWNER/NAME (gh reads only)
#   PR       the pull request number
#
# Writes into EV: started_utc, ended_utc, submit.json, exec, wait.json,
# watch.txt (cli), before.txt/after.txt (the remote's refs: on seeded-pr every
# refs/heads/* and the PR's head ref; on public-pr the PR's head ref and any
# kata/* branch, plus the PR's comment and review counts from the forge),
# verify-output.json, review.json, head.txt, score.json + score-row.txt,
# stages.txt, turns.txt, spend.toml (`ledger.py record`: the record's
# tokens_recorded, unmetered_calls, cost_recorded and, when estimated,
# cost_recorded_usd lines), pins.txt, oracles.txt (one PASS/FAIL
# line per oracle). Exit 0 only when every oracle passes. Spends one review
# (two agent turns, plus any validation retries) on the clone's agent.
set -euo pipefail
[ $# -eq 5 ] || { echo "usage: e1-run.sh EV CASE SURFACE REPO PR" >&2; exit 2; }
EV=$1 CASE=$2 SURFACE=$3 REPO=$4 PR=$5
K=$(cd -P -- "$(dirname -- "$0")" && pwd)
case $CASE in seeded-pr) SEEDED=$K/seeded.json ;; public-pr) SEEDED=$K/seeded-public.json ;;
*) echo "CASE is seeded-pr or public-pr" >&2; exit 2 ;; esac
case $SURFACE in cli | rest) ;; *) echo "SURFACE is cli or rest" >&2; exit 2 ;; esac
D=$PWD/.kata/data
[ -f "$D/operational.db" ] || { echo "run from the clone: no $D/operational.db" >&2; exit 2; }
mkdir "$EV"

remote_refs() {
	# Only refs kata could write or a run depends on: every branch (kata pushes only
	# refs/heads/*) and this PR's head. GitHub-managed refs (refs/pull/*/merge) are
	# regenerated by the forge at will and would fail a run kata did not touch.
	if [ "$CASE" = seeded-pr ]; then
		git ls-remote origin 'refs/heads/*' "refs/pull/$PR/head"
	else
		git ls-remote origin "refs/pull/$PR/head" 'refs/heads/kata/*'
		echo "comments $(gh api "repos/$REPO/issues/$PR/comments" --paginate --jq length | awk '{s += $1} END {print s + 0}')"
		echo "reviews $(gh api "repos/$REPO/pulls/$PR/reviews" --paginate --jq length | awk '{s += $1} END {print s + 0}')"
		echo "review_comments $(gh api "repos/$REPO/pulls/$PR/comments" --paginate --jq length | awk '{s += $1} END {print s + 0}')"
	fi
}

remote_refs >"$EV/before.txt"
HEADOID=$(gh pr view "$PR" --repo "$REPO" --json headRefOid -q .headRefOid)
echo "$HEADOID" >"$EV/forge-head.txt"
date -u +%Y-%m-%dT%H:%M:%SZ >"$EV/started_utc"
t0=$(date +%s)
if [ "$SURFACE" = cli ]; then
	kata run review --target "pr:$PR" --submit >"$EV/submit.json"
else
	curl -sS --fail-with-body -X POST http://127.0.0.1:8400/api/v1/executions \
		-H 'content-type: application/json' \
		-d "{\"workflow_ref\":\"review\",\"target\":\"pr:$PR\"}" >"$EV/submit.json"
fi
EXEC=$(python3 -I -c '
import json, sys
for line in reversed(sys.stdin.read().splitlines()):
    try:
        doc = json.loads(line)
    except ValueError:
        continue
    for key in ("id", "execution_id"):
        if isinstance(doc.get(key), str):
            print(doc[key]); sys.exit(0)
sys.exit("no execution id in the submit answer")' <"$EV/submit.json")
echo "$EXEC" >"$EV/exec"
echo "e1-run: $CASE $SURFACE execution $EXEC"
if [ "$SURFACE" = cli ]; then
	kata watch "$EXEC" --timeout-secs 7200 >"$EV/watch.txt" 2>&1 || true
fi
# Terminal BEFORE any oracle reads (RF7): the REST answer returns at submission.
# `kata run wait` exits non-zero on a failed execution (5, measured) and on its own
# timeout; either way the run is judged below, never skipped.
rc=0
kata run wait "$EXEC" --timeout-secs 7200 >"$EV/wait.json" || rc=$?
echo "$rc" >"$EV/wait.rc"
date -u +%Y-%m-%dT%H:%M:%SZ >"$EV/ended_utc"
echo $(($(date +%s) - t0)) >"$EV/wall_seconds"
remote_refs >"$EV/after.txt"
git for-each-ref refs/kata/targets >"$EV/pins.txt"

set +e
fails=0
oracle() { if [ "$2" = 0 ]; then echo "PASS $1" | tee -a "$EV/oracles.txt"; else echo "FAIL $1${3:+: $3}" | tee -a "$EV/oracles.txt"; fails=$((fails + 1)); fi; }

state=$(python3 -I "$K/ledger.py" "$D" execs | awk -v e="$EXEC" '$1 == e {print $4}')
[ "$state" = completed ]
oracle terminal-completed $? "state $state"
python3 -I "$K/ledger.py" "$D" head "$EXEC" >"$EV/head.txt"
grep -q "^frozen_head  $HEADOID\$" "$EV/head.txt"
oracle frozen-head-is-forge-head $? "forge $HEADOID; $(grep frozen_head "$EV/head.txt")"
kata run output "$EXEC" verify >"$EV/verify-output.json"
python3 -I -c 'import json,sys; json.dump(json.load(sys.stdin)["parsed"], sys.stdout)' \
	<"$EV/verify-output.json" >"$EV/review.json"
git fetch -q origin "refs/pull/$PR/head"
python3 -I "$K/score-e1.py" "$EV/review.json" "$SEEDED" --repo . --head "$HEADOID" \
	>"$EV/score.json" 2>"$EV/score-row.txt"
oracle review-validates-and-scores $? "$(cat "$EV/score-row.txt")"
diff "$EV/before.txt" "$EV/after.txt" >"$EV/remote-diff.txt"
oracle remote-unchanged $? "$(head -c 400 "$EV/remote-diff.txt")"
[ ! -s "$EV/pins.txt" ]
oracle no-target-pin-left $? "$(head -c 400 "$EV/pins.txt")"
python3 -I "$K/ledger.py" "$D" stages "$EXEC" >"$EV/stages.txt"
oracle stages-read $?
python3 -I "$K/ledger.py" "$D" turns "$EXEC" >"$EV/turns.txt"
oracle turns-read $?
python3 -I "$K/ledger.py" "$D" record "$EXEC" >"$EV/spend.toml"
oracle spend-read $?
set -e
echo "e1-run: $fails oracle(s) failed; seeded row: $(cat "$EV/score-row.txt")"
[ "$fails" = 0 ]
